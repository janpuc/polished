"""Writes spec/api/openapi.yaml from the routes and response models in src/polished/api/.

uv run python scripts/make_api_spec.py           # write the file
uv run python scripts/make_api_spec.py --check   # exit 1 when the file is out of date
"""

import sys
from pathlib import Path

import yaml

from polished.api.openapi import build_spec
from polished.config import Settings
from polished.server import create_app


class Dumper(yaml.SafeDumper):
    """Multi-line text as a literal block, which reads better than escaped quotes."""


def _text(dumper: yaml.SafeDumper, data: str) -> yaml.ScalarNode:
    return dumper.represent_scalar(
        "tag:yaml.org,2002:str", data, style="|" if "\n" in data else None
    )


Dumper.add_representer(str, _text)
SPEC = Path(__file__).resolve().parents[1] / "spec" / "api" / "openapi.yaml"


def render() -> str:
    """The spec of an app with every optional route switched on (the universal-link file, the
    test reset), so they are documented too."""
    settings = Settings(
        _env_file=None,
        public_url="http://localhost:8080",
        auth_mode="none",
        session_secret="spec-spec-spec-spec-spec-spec-spec-0",
        apple_team_id="ABCDE12345",
        test_reset_from="template.db",
        sync_enabled=False,
    )
    header = "# Generated by scripts/make_api_spec.py from src/polished/api/. Do not edit.\n"
    return header + yaml.dump(
        build_spec(create_app(settings)),
        Dumper=Dumper,
        sort_keys=False,
        allow_unicode=True,
        width=100,
    )


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if SPEC.read_text() == text else 1)
    SPEC.write_text(text)
    print(f"wrote {SPEC}")
